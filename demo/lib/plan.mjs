// The shot list for the footage scenes (2–9). build.mjs turns it into timed GSAP beats.
//
// at:     seconds from the scene's start, or { say: 'words' } for the moment the narration
//         reaches those words (dx shifts it; edge: 'end' uses the end of the phrase).
// still:  cross-fade to a capture (assets/shots/<name>.png).
// cam:    'full', 'still#target' or [x, y, w, h] in CSS pixels; zoom caps the scale.
// cursor: glide the synthetic pointer to a target's centre (or [x, y]); click: press there.
// mark:   outline a target for dur seconds, with an optional label.
// drag:   lift a chip image and carry it from one target to another.
// type:   step through typing stills.  keys: a keycap overlay.  note: a caption over the frame.
//
// Targets are boxes capture.mjs measured on the real page, so the pointer and camera land on
// the real control. Every still in a scene shares one coordinate system (the page, scrolled to 0).

const say = ( words, dx = 0, edge = 'start' ) => ( { say: words, dx, edge } );

